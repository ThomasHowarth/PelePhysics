"""Write reference.H: Cantera surface rates for the SurfaceEval test.

Run from this directory after changing the state or the ptcombust mechanism:

    python make_reference.py
"""

import pathlib
import shutil
import subprocess

import cantera as ct
import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
MECH = HERE.parents[2] / "Mechanisms" / "ptcombust" / "mechanism.yaml"

TEMPERATURE = 900.0  # K
PRESSURE = ct.one_atm  # Pa
GAS_X = "CH4:0.095, O2:0.21, N2:0.695"


def array(name, values):
    """Return a C++ array definition."""
    body = ", ".join(f"{v:.17g}" for v in values)
    return f"constexpr amrex::Real {name}[] = {{{body}}};"


def main():
    """Compute the reference values and write reference.H."""
    surf = ct.Interface(MECH, "Pt_surf")
    gas = surf.adjacent["gas"]
    gas.TPX = TEMPERATURE, PRESSURE, GAS_X
    surf.TP = TEMPERATURE, PRESSURE
    sizes = np.array([sp.size for sp in surf.species()])
    n_gas = gas.n_species
    mw = gas.molecular_weights  # kg/kmol

    def rates():
        """Gas mass fluxes [g/cm^2/s] and coverage rates [1/s]."""
        sdot = dict(zip(surf.kinetics_species_names, surf.net_production_rates))
        sdot_gas = np.array([sdot[n] for n in gas.species_names])
        sdot_surf = np.array([sdot[n] for n in surf.species_names])
        # kmol/m^2/s * kg/kmol = kg/m^2/s -> g/cm^2/s
        flux = 0.1 * sdot_gas * mw
        dthetadt = sdot_surf * sizes / surf.site_density
        return flux, dthetadt

    # rates at fixed, arbitrary coverages
    theta = np.linspace(1.0, 2.0, surf.n_species)
    theta /= theta.sum()
    surf.coverages = theta
    flux, dthetadt = rates()

    # steady coverages from a bare surface, tightly converged
    theta0 = np.zeros(surf.n_species)
    theta0[surf.species_index("PT(S)")] = 1.0
    surf.coverages = theta0
    surf.advance_coverages_to_steady_state()
    for _ in range(5):
        surf.advance_coverages(1.0e10)
    theta_ss = surf.coverages
    flux_ss, dthetadt_ss = rates()
    assert np.max(np.abs(dthetadt_ss)) < 1e-6, dthetadt_ss

    lines = [
        "// Generated by make_reference.py with Cantera " + ct.__version__,
        "#ifndef SURFACEEVAL_REFERENCE_H",
        "#define SURFACEEVAL_REFERENCE_H",
        "#include <AMReX_REAL.H>",
        "namespace reference {",
        f"constexpr int n_gas = {n_gas};",
        f"constexpr int n_surf = {surf.n_species};",
        f"constexpr amrex::Real T = {TEMPERATURE:.17g};",
        # kg/m^3 -> g/cm^3
        f"constexpr amrex::Real rho = {gas.density * 1.0e-3:.17g};",
        array("Y", gas.Y),
        array("theta", theta),
        array("flux", flux),
        array("dthetadt", dthetadt),
        array("theta0", theta0),
        array("theta_ss", theta_ss),
        array("flux_ss", flux_ss),
        "} // namespace reference",
        "#endif",
    ]
    out = HERE / "reference.H"
    out.write_text("\n".join(lines) + "\n")
    if shutil.which("clang-format"):
        subprocess.run(["clang-format", "-i", str(out)], check=True)


if __name__ == "__main__":
    main()
